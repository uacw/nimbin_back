package tech.nimbus.models

import kotlinx.serialization.Serializable

/**
 * Типы видимости заметок в системе.
 *
 * Определяет уровень доступности заметки для различных пользователей:
 * - PUBLIC: заметка видна всем пользователям и отображается в публичных списках
 * - UNLISTED: заметка доступна всем по прямой ссылке (ID), но не отображается в публичных списках
 * - PRIVATE: заметка доступна только владельцу (требует аутентификации)
 */
@Serializable
enum class PasteVisibility {
    /**
     * Публичная заметка.
     * - Видна всем пользователям
     * - Отображается в публичных списках (/api/pastes/public)
     * - Доступна без аутентификации
     */
    PUBLIC,

    /**
     * Скрытая заметка (unlisted).
     * - Доступна всем по прямой ссылке (по ID)
     * - НЕ отображается в публичных списках
     * - Доступна без аутентификации при знании ID
     * - Полезна для конфиденциального обмена ссылками
     */
    UNLISTED,

    /**
     * Приватная заметка.
     * - Доступна только владельцу
     * - Требует аутентификации и проверки прав доступа
     * - НЕ отображается в публичных списках
     * - Отображается только в персональных списках владельца
     */
    PRIVATE
}
